/** 偏好里的 lang 解析成实际语言。 */
function resolve(pref) {
  if (LANGS.includes(pref)) return pref;
  let tags = [];
  try { tags = navigator.languages ?? [navigator.language ?? '']; } catch (error) { tags = []; }
  for (const tag of tags) {
    // 繁中先判，否则会被 ^zh 吃掉
    if (/^zh-(hant|tw|hk|mo)\b/i.test(tag)) return 'zh-Hant';
    if (/^zh\b|^zh-/i.test(tag)) return 'zh';
    if (/^ja\b|^ja-/i.test(tag)) return 'ja';
    if (/^ko\b|^ko-/i.test(tag)) return 'ko';
    if (/^de\b|^de-/i.test(tag)) return 'de';
    if (/^fr\b|^fr-/i.test(tag)) return 'fr';
    if (/^it\b|^it-/i.test(tag)) return 'it';
    if (/^ru\b|^ru-/i.test(tag)) return 'ru';
    if (/^pt\b|^pt-/i.test(tag)) return 'pt-BR';
    if (/^es\b|^es-/i.test(tag)) return 'es-419';
    if (/^en\b|^en-/i.test(tag)) return 'en';
  }
  return 'en';
}

/** 上一次解析用的原始偏好串，用来判断要不要重新解析（一次 localStorage 读很便宜）。 */
let memoRaw = null;
let memoLang = 'zh';

/** 当前该用的语言。 */
export function currentLang() {
  let raw = '';
  try { raw = window.localStorage.getItem(PREFS_KEY) ?? ''; } catch (error) { raw = ''; }
  if (raw !== memoRaw) {
    memoRaw = raw;
    let pref = 'auto';
    try { pref = JSON.parse(raw)?.lang ?? 'auto'; } catch (error) { pref = 'auto'; }
    memoLang = resolve(pref);
  }
  return memoLang;
}

/**
 * 取一条文案。vars 里的 {name} 会被替换。
 * 语言表里没有的键返回键本身——方便一眼看出漏翻的地方。
 */
export function t(key, vars) {
  const lang = currentLang();
  const table = DICT[lang] ?? DICT.zh;
  // 缺键时先回落到该语言指定的语言，再落到英文，最后才是中文与键名本身
  const fallback = DICT[FALLBACK[lang]] ?? DICT.en;
  const text = table[key] ?? fallback[key] ?? DICT.en[key] ?? DICT.zh[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

